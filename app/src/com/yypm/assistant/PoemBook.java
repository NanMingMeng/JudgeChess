    /** 按标题精确匹配，返回「朝代·作者\n全文」；未命中返回 null。 */
    public static String find(String title) {
        if (title == null || title.isEmpty()) return null;
        for (String p : POEMS) {
            int i = p.indexOf('|');
            if (i < 0) continue;
            String t = p.substring(0, i);
            if (t.equals(title) || title.startsWith(t) || t.startsWith(title)) {
                int j = p.indexOf('|', i + 1);
                return p.substring(i + 1, j) + "\n" + p.substring(j + 1);
            }
        }
        return null;
    }
